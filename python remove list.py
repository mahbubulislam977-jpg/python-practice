# The remove() method removes the specified item.


# The pop() method removes the specified item.
thislist = [" sahed","thin","hasan"]
thislist.pop()
print(thislist)


# The del keyworld also removes the specified item.
del thislist[1]
print(thislist)

# The clear() method emptes the list.
thislist = [" sahed","thin","hasan"]
thislist.clear()
print(thislist)